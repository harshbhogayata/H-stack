#!/usr/bin/env node
// HS-010 Model Experience note: the exact text each hook injects, its token cost and cache effect,
// rendered from the snapshot expectations into hooks/README.md. --check fails when stale.
import fs from 'node:fs';
import path from 'node:path';
import { allCases } from './snapshot.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const tokens = (s) => Math.ceil(Buffer.byteLength(String(s || '')) / 3);
const CACHE = {
  'session-start.mjs': 'Once per session start; static map first and byte-stable, facts sorted. Part of the cached prefix after the first turn.',
  'classify.mjs': 'Appended after the prompt; nothing for direct prompts. Never edits earlier context.',
  'gate-bash.mjs': 'Decision text only, shown with the tool result; no prefix change.',
  'gate-edit.mjs': 'Decision text only, shown with the tool result; no prefix change.',
  'gate-fetch.mjs': 'Decision text only.', 'gate-mcp.mjs': 'Decision text only.', 'gate-skill.mjs': 'Decision text only.',
  'ledger.mjs': 'Appended next to the tool result; at most one note per kind per turn.',
  'batch.mjs': 'Appended once per batch, only when the receipt digest changed.',
  'taint.mjs': 'One provenance line per turn.', 'failure.mjs': 'Only on interrupts.', 'syntax.mjs': 'Only when an edit introduces a new parse error.',
  'memory-shadow.mjs': 'Only when an auto-memory rewrite drops specifics.', 'agent-result.mjs': 'Only when a validated subagent output is malformed or thin.',
  'subagent-start.mjs': 'Once per subagent, deterministic for the same inputs.', 'stop.mjs': 'Block reason only when the stop gate blocks (at most once per stop).',
  'pre-compact.mjs': 'Static compaction instructions.', 'post-compact.mjs': 'Writes a file; injects nothing.', 'session-end.mjs': 'Injects nothing.',
};
function text(stdout) { try { const j = JSON.parse(stdout.trim()); return j.hookSpecificOutput?.additionalContext || j.hookSpecificOutput?.permissionDecisionReason || j.reason || ''; } catch { return stdout.trim(); } }

export function render() {
  const out = ['# H-Stack hooks: Model Experience', '', 'Generated by `scripts/model-experience.mjs` from the snapshot fixtures. Each row is the exact text Claude sees for that fixture, its cost at `ceil(bytes / 3)` tokens, and its cache effect. Hooks not listed inject nothing for their fixtures.', ''];
  const byHook = new Map();
  for (const c of allCases()) {
    const exp = c.file.replace(/\.json$/, '.expected');
    if (!fs.existsSync(exp)) continue;
    const t = text(fs.readFileSync(exp, 'utf8'));
    if (!t) continue;
    if (!byHook.has(c.hook)) byHook.set(c.hook, []);
    byHook.get(c.hook).push({ name: c.name, t });
  }
  for (const hook of [...byHook.keys()].sort()) {
    out.push(`## ${hook}`, '', `Cache effect: ${CACHE[hook] || 'n/a'}`, '', '| fixture | tokens | text |', '|---|---:|---|');
    for (const r of byHook.get(hook)) out.push(`| ${r.name} | ${tokens(r.t)} | ${r.t.replace(/\|/g, '\\|').replace(/\n/g, '<br>')} |`);
    out.push('');
  }
  return out.join('\n');
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const file = path.join(ROOT, 'hooks', 'README.md');
  const md = render();
  if (process.argv.includes('--check')) {
    const ok = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === md;
    console.log(JSON.stringify({ status: ok ? 'ok' : 'fail', reason: ok ? 'hooks/README.md current' : 'hooks/README.md stale; run scripts/model-experience.mjs' }));
    process.exit(ok ? 0 : 1);
  }
  fs.writeFileSync(file, md);
  console.log(JSON.stringify({ status: 'ok', reason: 'wrote hooks/README.md' }));
}
