#!/usr/bin/env node
// Summarises the latest iteration of every per-skill benchmark into evals/results/skills/SUMMARY.md.
import fs from 'node:fs';
import path from 'node:path';
const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(REPO, 'evals', 'results', 'skills');
const rows = [];
for (const skill of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  const iters = fs.readdirSync(path.join(dir, skill)).filter((d) => /^iteration-\d+$/.test(d)).sort((a, b) => Number(b.split('-')[1]) - Number(a.split('-')[1]));
  const it = iters.find((d) => fs.existsSync(path.join(dir, skill, d, 'benchmark.json')));
  if (!it) continue;
  const b = JSON.parse(fs.readFileSync(path.join(dir, skill, it, 'benchmark.json'), 'utf8'));
  const s = b.run_summary;
  const verdict = s.with_skill.pass_rate.mean > s.without_skill.pass_rate.mean ? 'kept (better)' : s.with_skill.pass_rate.mean === s.without_skill.pass_rate.mean ? 'kept (tie: no measured gain)' : 'DROP (worse than no skill)';
  rows.push(`| ${skill} | ${it} | ${b.metadata.evals_run.length} | ${s.with_skill.pass_rate.mean.toFixed(2)} | ${s.without_skill.pass_rate.mean.toFixed(2)} | ${s.delta.pass_rate} | ${s.delta.time_seconds}s | ${s.delta.tokens} | ${verdict} |`);
}
const md = ['# Per-skill benchmarks (light: 1 run per arm per eval)', '', 'Generated by `node evals/bench-summary.mjs` from `evals/results/skills/<skill>/iteration-N/benchmark.json`. With one run per arm, a delta under about 0.15 is within noise.', '', '| skill | iteration | evals | with | without | Δ pass rate | Δ time | Δ tokens | verdict |', '|---|---|---:|---:|---:|---:|---:|---:|---|', ...rows, ''].join('\n');
fs.writeFileSync(path.join(dir, 'SUMMARY.md'), md);
console.log(md);
